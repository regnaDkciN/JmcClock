/*******************************************************************************
* SaveSwatch()
*
* Saves a rectangular swatch from a larger canvas to a smaller canvas.
*
* Arguments:
*   rDest   The smaller canvas which receive a swatch of the larger canvas (rScr).
*   rScr    The larger canvas from which a swatch will be taken.
*   xOfst   The X offset into rSrc where the swatch will start.
*   yOfst   The Y offset into rSrc where the swatch will start.
*******************************************************************************/
static void SaveSwatch(GFXcanvas16 &rDest, GFXcanvas16 &rSrc, int16_t xOfst,
                       int16_t yOfst)
{
    // Get pointers into each of our canvases.
    uint16_t *pDest = rDest.getBuffer();
    uint16_t *pSrc  = rSrc.getBuffer();

    // Copy a piece of the larger canvas into the smaller canvas.
    for (uint16_t i = 0; i < rDest.height(); i++)
    {
        memcpy(pDest + (i * rDest.width()),
               pSrc + rSrc.width() * (yOfst + i) + xOfst,
               rDest.width() * 2);
    }
} // End SaveSwatch().


/*******************************************************************************
* ScrollFromRight()
*
* Scrolls text from off screen at the right until it is centered on the screen.
*
* Arguments:
*   rBgCanvas   The canvas containing the background which will have the text
*               scrolled across it.
*   pTxt        Pointer to the text string to be scrolled.
*   pFont       Pointer to the font used to display the text (pTxt).
*   fontSize    The size multiplier for displaying the text font.
*   fontColor   The color to print the text.
*   yOffset     The Y offset into rBgCanvas that the text will scroll.
*******************************************************************************/
static void ScrollFromRight(GFXcanvas16 &rBgCanvas, const char *pTxt,
                            const GFXfont *pFont, uint8_t fontSize,
                            uint16_t fontColor, int16_t yOffset)
{
    // Init some useful variables.
    int16_t  x = 0;
    int16_t  y = 0;
    uint16_t w = 0;
    uint16_t h = 0;
    uint16_t scrW = gTft.width();

    // Calculate the size of the welcome text.
    gTft.setFont(pFont);
    gTft.setTextSize(fontSize);
    gTft.getTextBounds(pTxt, 0, 0, &x, &y, &w, &h);

    // Calculate the size of the swatch that we'll use for scrolling the text.
    // We want to end up with the text centered horizontally on the screen.
    uint16_t swatchW = scrW - ((scrW - w) / 2);
    uint16_t swatchH = h;

    // Create a canvas to hold the backgound where we'll be scrolling the text
    // and fill it in with the corresponding background screen info.
    GFXcanvas16 refCanvas(swatchW, swatchH);
    SaveSwatch(refCanvas, rBgCanvas, scrW - swatchW, yOffset);

    // Create a canvas to actually scroll the text in.
    GFXcanvas16 workingCanvas(swatchW, swatchH);

    // Get the font ready for scrolling.
    gCanvas.setTextColor(fontColor);
    workingCanvas.setFont(pFont);
    workingCanvas.setTextSize(fontSize);

    // Scroll title information from the right of the screen.
    for (int16_t i = swatchW; i >= 0; i--)
    {
        SaveSwatch(workingCanvas, refCanvas, 0, 0);
        workingCanvas.setCursor(i - x, -y);
        workingCanvas.print(pTxt);
        gTft.drawRGBBitmap(scrW - swatchW, yOffset, workingCanvas.getBuffer(),
                           workingCanvas.width(), workingCanvas.height());
    }
} // End ScrollFromRight().


/*******************************************************************************
* ShowWelcome()
*
* Shows a bitmapped background with welcome and copyright text.
*******************************************************************************/
void ClockWelcome::ShowWelcome()
{
    const char   *pWelcomeString   = "JMC  CLOCK";
    const char   *pCopyrightString = "Copyright (c) 2026, J. M. Corbett";
    const int16_t welcomeYOffset   = 70;
    const int16_t copyrightYOffset = 190;
    const uint16_t TEXT_COLOR      = 0xffff;
    const uint16_t BG_COLOR        = 0x001f;

    // Draw the background screen.
    gTft.fillScreen(BG_COLOR);
    gCanvas.drawBitmap(0, 0, WelcomeBitmap, 320, 240, 0, BG_COLOR);
    gTft.drawRGBBitmap(0, 0, gCanvas.getBuffer(), gCanvas.width(), gCanvas.height());

    // Scroll the welcome string.
    ScrollFromRight(gCanvas, pWelcomeString, &FreeSerifBoldItalic24pt7b, 1,
                    TEXT_COLOR, welcomeYOffset);

    // Scroll the copyright string.
    ScrollFromRight(gCanvas, pCopyrightString, &FreeSerifBoldItalic9pt7b, 1,
                    TEXT_COLOR, copyrightYOffset);
} // End ShowWelcome().
